// An argument, a tree that cannot be read and a file that cannot be written
// are exit 2, and nothing is written.
func TestATreeItCannotReadOrWriteIsExit2(t *testing.T) {
	for _, c := range []struct {
		name string
		tree fstest.MapFS
		want string
	}{
		{"no go.mod", fstest.MapFS{"internal/slices/guard/command.go": {Data: []byte("package guard\n")}}, "go.mod"},
		{"a go.mod naming no module", fstest.MapFS{"go.mod": {Data: []byte("go 1.27\n")}}, "go.mod names no module"},
		{"no slices", fstest.MapFS{"go.mod": {Data: []byte("module m\n")}, "internal/cli/a.go": {Data: []byte("package cli\n")}}, sliceRoot},
		{"a file that does not parse", treeOf(map[string]string{"internal/cli/broken.go": "package cli\n\nvar = \n"}), "internal/cli/broken.go"},
		{"a slice's file that does not parse", treeOf(map[string]string{"internal/slices/guard/broken.go": "package guard\n\nfunc {\n"}), "internal/slices/guard/broken.go"},
		{"a subpackage's file that does not parse", treeOf(map[string]string{"internal/slices/guard/domain/broken.go": "package\n"}), "internal/slices/guard/domain/broken.go"},
	} {
		code, stderr, file := generate(t, c.tree, false)
		if code != 2 || file != "" || !strings.Contains(stderr, c.want) {
			t.Errorf("%s: exit %d, %q, wrote %q; want 2 naming %q and nothing written", c.name, code, stderr, file, c.want)
		}
	}
	var stderr strings.Builder
	failing := func(string, []byte) error { return errors.New("disk full") }
	if code := run(treeOf(map[string]string{}), failing, false, nil, &stderr); code != 2 || !strings.Contains(stderr.String(), "disk full") {
		t.Errorf("a write that fails: exit %d, %q; want 2 saying why", code, stderr.String())
	}
	stderr.Reset()
	if code := run(treeOf(map[string]string{}), failing, false, []string{"extra"}, &stderr); code != 2 || !strings.Contains(stderr.String(), `unexpected argument "extra"`) {
		t.Errorf("an argument: exit %d, %q; want 2 naming it", code, stderr.String())
	}
}

