const declarePath = "github.com/donvargax/itos/v8/internal/declare"

// declaring is a Go file of package pkg declaring var variable, its Name and
// its Rank given as Go expressions, so a test can give one that is no
// literal.
func declaring(pkg, variable, name, rank string) string {
	return "package " + pkg + `

import "` + declarePath + `"

var ` + variable + ` = declare.Command{Name: ` + name + `, Rank: ` + rank + `, Lines: []string{"a line"}}
`
}

// treeOf is a repository of itos's module holding files, by their paths from
// its root, a file of internal/cli and a slice, unless files hold one.
func treeOf(files map[string]string) fstest.MapFS {
	tree := fstest.MapFS{
		"go.mod":              {Data: []byte("module github.com/donvargax/itos/v8\n\ngo 1.27\n")},
		"internal/cli/cli.go": {Data: []byte("package cli\n")},
	}
	if _, ok := files["internal/slices/guard/command.go"]; !ok {
		tree["internal/slices/guard/command.go"] = &fstest.MapFile{Data: []byte(declaring("guard", "Command", `"guard"`, "900"))}
	}
	for name, text := range files {
		tree[name] = &fstest.MapFile{Data: []byte(text)}
	}
	return tree
}

// generate runs assemble over tree and returns its exit status, what it said
// and the file it wrote, "" when it wrote none.
func generate(t *testing.T, tree fstest.MapFS, check bool) (int, string, string) {
	t.Helper()
	var stderr strings.Builder
	written := ""
	write := func(name string, data []byte) error {
		if name != output {
			t.Errorf("wrote %s, want %s", name, output)
		}
		written = string(data)
		tree[name] = &fstest.MapFile{Data: data}
		return nil
	}
	code := run(tree, write, check, nil, &stderr)
	return code, stderr.String(), written
}

// The table lists every declaration, internal/cli's by its variable and a
// slice's by its package aliased <package>slice, in Rank order, and
// dispatches each name to run<Pascal(Name)> in that order. internal/cli's
// tests and generated file, a slice's tests and a variable that is no
// declare.Command literal are not read as declarations.
func TestTheTableListsEveryDeclarationInRankOrder(t *testing.T) {
	tree := treeOf(map[string]string{
		"internal/cli/declare_task.go":         declaring("cli", "taskDeclared", `"task"`, "10"),
		"internal/cli/declare_git_shim.go":     "package cli\n\nimport d \"" + declarePath + "\"\n\nvar gitShimDeclared = d.Command{Name: \"git-shim\", Rank: 0x1e}\n",
		"internal/cli/group.go":                "package cli\n\nimport \"" + declarePath + "\"\n\nvar (\n\tother = 3\n\tpushDeclared, pinDeclared = declare.Command{Name: \"push\", Rank: 50}, declare.Command{Name: \"pin\", Rank: 40}\n\tnotOne = declare.Spec{}\n\tlisted = []int{1}\n\tsplit, pair = twice()\n)\n",
		"internal/cli/declare_task_test.go":    declaring("cli", "testDeclared", `"tested"`, "1"),
		"internal/cli/commands_gen.go":         declaring("cli", "genDeclared", `"generated"`, "2"),
		"internal/cli/other.go":                "package cli\n\nvar elsewhere = declare.Command{Name: \"elsewhere\", Rank: 3}\n",
		"internal/cli/README.md":               "not Go\n",
		"internal/slices/guard/command.go":     declaring("guard", "Command", `"guard"`, "20"),
		"internal/slices/guard/guard_test.go":  declaring("guard", "Command", `"tested"`, "4"),
		"internal/slices/watch/command.go":     declaring("ciwatch", "Command", `"watch"`, "60"),
		"internal/slices/watch/domain/rule.go": "package domain\n",
		"internal/slices/watch/testdata/x.go":  declaring("x", "Command", `"fixture"`, "5"),
		"internal/slices/README.md":            "not a slice\n",
	})
	code, stderr, file := generate(t, tree, false)
	if code != 0 {
		t.Fatalf("exit %d: %s", code, stderr)
	}
	want := `// Code generated by tools/bin/assemble from the command declarations; DO NOT EDIT.
// Run go run ./tools/bin/assemble after adding, removing, renaming or re-ranking one.

package cli

import (
	"github.com/donvargax/itos/v8/internal/declare"
	guardslice "github.com/donvargax/itos/v8/internal/slices/guard"
	ciwatchslice "github.com/donvargax/itos/v8/internal/slices/watch"
)

// declared is every command's declaration, in Rank order: itos --help's.
var declared = []declare.Command{
	taskDeclared,
	guardslice.Command,
	gitShimDeclared,
	pinDeclared,
	pushDeclared,
	ciwatchslice.Command,
}

// dispatch is the run function of the command name names, false when
// none is.
func dispatch(name string) (command, bool) {
	switch name {
	case "task":
		return runTask, true
	case "guard":
		return runGuard, true
	case "git-shim":
		return runGitShim, true
	case "pin":
		return runPin, true
	case "push":
		return runPush, true
	case "watch":
		return runWatch, true
	}
	return nil, false
}
`
	if file != want {
		t.Errorf("the file:\n%s\nwant:\n%s", file, want)
	}
	if code, stderr, _ := generate(t, tree, true); code != 0 {
		t.Errorf("-check over the file it wrote: exit %d, %s", code, stderr)
	}
}

// With no declaration in internal/cli, the table is the slices' alone.
func TestATreeOfSlicesAloneHasATable(t *testing.T) {
	code, stderr, file := generate(t, treeOf(map[string]string{}), false)
	if code != 0 || !strings.Contains(file, "\tguardslice.Command,\n}") || !strings.Contains(file, "return runGuard, true") {
		t.Errorf("exit %d, %s, the file:\n%s", code, stderr, file)
	}
}

// -check writes nothing, and fails naming the file when it is missing or not
// what assemble writes.
func TestCheckRefusesAFileThatIsNotCurrent(t *testing.T) {
	tree := treeOf(map[string]string{"internal/cli/declare_task.go": declaring("cli", "taskDeclared", `"task"`, "10")})
	if code, stderr, file := generate(t, tree, true); code != 1 || !strings.Contains(stderr, output+" is not what the command declarations make") || file != "" {
		t.Errorf("a missing file: exit %d, %q, wrote %q; want 1 naming %s and nothing written", code, stderr, file, output)
	}
	if code, _, _ := generate(t, tree, false); code != 0 {
		t.Fatal("cannot write the file")
	}
	tree[output] = &fstest.MapFile{Data: []byte("package cli\n")}
	if code, stderr, file := generate(t, tree, true); code != 1 || !strings.Contains(stderr, output) || file != "" {
		t.Errorf("a stale file: exit %d, %q, wrote %q; want 1 naming %s and nothing written", code, stderr, file, output)
	}
}

// A declaration assemble cannot assemble is refused, naming its file or
// files, and nothing is written.
func TestADeclarationItCannotAssembleIsRefusedByFile(t *testing.T) {
	task := declaring("cli", "taskDeclared", `"task"`, "10")
	for _, c := range []struct {
		name  string
		files map[string]string
		want  string
	}{
		{"a Name that is no literal", map[string]string{
			"internal/cli/declare_task.go": declaring("cli", "taskDeclared", "name", "10"),
		}, "internal/cli/declare_task.go: taskDeclared names its command by no string literal"},
		{"an empty Name", map[string]string{
			"internal/cli/declare_task.go": declaring("cli", "taskDeclared", `""`, "10"),
		}, "internal/cli/declare_task.go: taskDeclared names its command by no string literal"},
		{"a Rank that is no literal", map[string]string{
			"internal/cli/declare_task.go": declaring("cli", "taskDeclared", `"task"`, "rank"),
		}, "internal/cli/declare_task.go: taskDeclared ranks its command by no integer literal"},
		{"a Rank that is no integer", map[string]string{
			"internal/cli/declare_task.go": declaring("cli", "taskDeclared", `"task"`, `"10"`),
		}, "internal/cli/declare_task.go: taskDeclared ranks its command by no integer literal"},
		{"a Rank out of range", map[string]string{
			"internal/cli/declare_task.go": declaring("cli", "taskDeclared", `"task"`, "99999999999999999999"),
		}, "internal/cli/declare_task.go: taskDeclared ranks its command by no integer literal"},
		{"a literal by position", map[string]string{
			"internal/cli/declare_task.go": strings.Replace(task, `Name: "task", Rank: 10, Lines: []string{"a line"}`, `"task", 10`, 1),
		}, "internal/cli/declare_task.go: taskDeclared names its command by no string literal"},
		{"no Rank", map[string]string{
			"internal/cli/declare_task.go": strings.Replace(task, ", Rank: 10", "", 1),
		}, "internal/cli/declare_task.go: taskDeclared ranks its command by no integer literal"},
		{"a slice's Name that is no literal", map[string]string{
			"internal/slices/guard/command.go": declaring("guard", "Command", "name", "10"),
		}, "internal/slices/guard/command.go: Command names its command by no string literal"},
		{"a Name twice in internal/cli", map[string]string{
			"internal/cli/declare_task.go":  task,
			"internal/cli/declare_twice.go": declaring("cli", "twiceDeclared", `"task"`, "20"),
		}, `internal/cli/declare_task.go and internal/cli/declare_twice.go both declare the command "task": a name runs one command`},
		{"a Name in two slices", map[string]string{
			"internal/slices/guard/command.go": declaring("guard", "Command", `"guard"`, "10"),
			"internal/slices/ward/command.go":  declaring("ward", "Command", `"guard"`, "20"),
		}, `internal/slices/guard/command.go and internal/slices/ward/command.go both declare the command "guard"`},
		{"a Name in a slice and in internal/cli", map[string]string{
			"internal/cli/declare_guard.go": declaring("cli", "guardDeclared", `"guard"`, "10"),
		}, `internal/slices/guard/command.go and internal/cli/declare_guard.go both declare the command "guard": a command moved into its slice leaves internal/cli`},
		{"a Rank twice", map[string]string{
			"internal/cli/declare_task.go":     task,
			"internal/slices/guard/command.go": declaring("guard", "Command", `"guard"`, "10"),
		}, "internal/cli/declare_task.go and internal/slices/guard/command.go both rank their command 10"},
		{"a slice with no Command", map[string]string{
			"internal/slices/scrap/scrap.go":      "package scrap\n",
			"internal/slices/scrap/scrap_test.go": declaring("scrap", "Command", `"scrap"`, "10"),
			"internal/slices/scrap/other.go":      declaring("scrap", "Other", `"scrap"`, "10"),
		}, "internal/slices/scrap declares no command: give it a package-level var Command"},
		{"a declaration in a slice's subpackage", map[string]string{
			"internal/slices/guard/domain/command.go": declaring("domain", "Inner", `"inner"`, "10"),
		}, "internal/slices/guard/domain/command.go declares Inner in a subpackage of internal/slices/guard"},
		{"a refused declaration in a slice's subpackage", map[string]string{
			"internal/slices/guard/domain/deep/command.go": declaring("deep", "Command", "name", "10"),
		}, "internal/slices/guard/domain/deep/command.go: Command names its command by no string literal"},
	} {
		tree := treeOf(c.files)
		code, stderr, file := generate(t, tree, false)
		if code != 1 || file != "" {
			t.Errorf("%s: exit %d, wrote %q; want 1 and nothing written", c.name, code, file)
		}
		if !strings.Contains(stderr, c.want) {
			t.Errorf("%s: %q, want %q", c.name, stderr, c.want)
		}
		if code, _, _ := generate(t, tree, true); code != 1 {
			t.Errorf("%s: -check exit %d, want 1", c.name, code)
		}
	}
}

